// Bounded cyclic problems: enumerate every permitted wiring up to its first N
// arrivals or its authored deadline. Existing finite problem banks stay intact.
import {createHash} from 'node:crypto';
import {writeFileSync,mkdirSync} from 'node:fs';
import {returnChallenges} from '../src/content/return-challenges.js';
import {Simulation} from '../src/core/simulation.js';
import {returnPatternResult} from '../src/core/return-pattern.js';

export function returnWirings(challenge){
 const sets=[];
 for(let mask=0;mask<2**challenge.candidates.length;mask++){
  const ids=challenge.candidates.filter((_,i)=>mask&2**i).map(e=>e.id);
  if(ids.length<=challenge.limit)sets.push(ids);
 }
 return sets;
}
export function runReturn(challenge,ids){
 const run=new Simulation({mode:'spread',target:challenge.goal,nodes:challenge.nodes,edges:challenge.candidates.filter(e=>ids.includes(e.id))});
 const deadline=run.circuit.time.ticks(challenge.maxDuration);
 let steps=0;
 while(!run.exhausted&&run.nextTime<=deadline&&run.arrivals(challenge.goal).length<challenge.count){
  if(!run.hasFutureArrival(challenge.goal))break;
  if(++steps>1000||run.records.length>6000)throw Error('Return proof exceeded bounded event budget '+challenge.id);
  run.advanceNext();
 }
 return run;
}
export function inspectReturn(challenge,sets=returnWirings(challenge)){
 const clears=[];let highest=0;
 for(const ids of sets){
  const run=runReturn(challenge,ids),outcome=returnPatternResult(challenge,run);
  highest=Math.max(highest,Number(run.format()));
  if(outcome.state==='achieved')clears.push({time:outcome.actual,edges:ids,waited:run.records.some(e=>e.type==='process-start'&&Number(e.wait)>0)});
 }
 clears.sort((a,b)=>Number(a.time)-Number(b.time));
 const best=clears[0],winners=best?clears.filter(e=>e.time===best.time).length:0;
 return {legalWirings:sets.length,achieved:clears.length,winners,winner:best?.edges??[],baseline:best?.time??null,partial:clears.find(e=>Number(e.time)>Number(best.time))??null,waited:best?.waited??false,maximum:highest,valid:winners===1&&clears.some(e=>Number(e.time)>Number(best.time))};
}
const decimal=value=>String(Math.round(value*100)/100);
export function generateReturnChallenges(){
 const banks={},proof={kind:'first-N-return-pattern',stages:[]};
 for(const authored of returnChallenges){
  const sets=returnWirings(authored),bank=[],families=[];
  for(let family=0;family<2;family++)for(let variant=0;variant<4;variant++){
   const problem=structuredClone(authored),gap=Number(problem.interval),period=gap*(problem.limit===6?2:1);
   const process=Number(problem.nodes[0].process)+Number(problem.nodes[1].process)*2;
   const leg=Math.floor((period-process)/3*4)/4,remainder=period-process-leg*2;
   if(leg<.1)throw Error('Loop too short '+authored.id);
   const values={SA:leg,AC:leg,CS:remainder,SB:leg,BD:leg,DS:remainder,AG:.5+variant*.2,BG:.5+variant*.2+(problem.limit===6?gap:.8),SC:gap*3+.7,CG:gap*3+.9,SD:gap*3+.9,DG:gap*3+1.1,AD:gap*3+.3,BC:gap*3+.5};
   values[family===0?'DS':'CS']+=gap*.7+.3;
   if(problem.limit===6){
    values.CG=values.BG+gap-leg-Number(problem.nodes[1].process);
    if(family===1)values.SC=leg+Number(problem.nodes[1].process)+leg;
   }
   if(problem.limit===5){values[family===0?'AG':'BG']+=gap*2;values[family===0?'BG':'AG']=.5+variant*.2;}
   problem.candidates=problem.candidates.map(e=>({...e,time:decimal(values[e.id])}));
   const result=inspectReturn(problem,sets);
   console.log(authored.id+' family '+family+' variant '+variant+' winners='+result.winners+' clears='+result.achieved+' partial='+Boolean(result.partial));
   if(!result.valid)throw Error('Return problem needs revision '+JSON.stringify(result));
   if(variant===0)families.push(result.winner);
   const id=createHash('sha256').update(JSON.stringify({id:problem.id,version:problem.version,nodes:problem.nodes,candidates:problem.candidates,count:problem.count,interval:problem.interval,limit:problem.limit})).digest('hex').slice(0,16);
   bank.push({id,baseVersion:1,family,times:problem.candidates.map(e=>e.time),baseline:result.baseline,maxDuration:decimal(result.maximum)});
   proof.stages.push({challenge:authored.id,id,family,variant,...result});
  }
  if(JSON.stringify(families[0])===JSON.stringify(families[1]))throw Error('Same return-wiring families '+authored.id);
  banks[authored.id]=bank;
 }
 mkdirSync('設計検証/星への帰還',{recursive:true});
 writeFileSync('src/content/return-variants.js','// Generated by scripts/generate-return-challenges.js. Answers stay in proof artifacts.\nexport const returnVariants = '+JSON.stringify(banks,null,2)+';\n');
 writeFileSync('設計検証/星への帰還/proof.json',JSON.stringify(proof,null,2));
}
if(process.argv[1]?.replaceAll('\\','/').endsWith('/generate-return-challenges.js'))generateReturnChallenges();
